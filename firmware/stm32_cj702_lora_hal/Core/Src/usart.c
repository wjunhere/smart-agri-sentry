void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART2) {
        uint8_t b = s_rx_tmp;
        if (s_cj702_idx == 0 && b != CJ702_HEADER_0) {
            /* wait for header */
        } else if (s_cj702_idx == 1 && b != CJ702_HEADER_1) {
            s_cj702_idx = 0;
        } else {
            s_cj702_raw[s_cj702_idx++] = b;
            if (s_cj702_idx >= CJ702_FRAME_LEN) {
                cj702_data_t parsed;
                if (cj702_parse(s_cj702_raw, &parsed)) {
                    g_last_sample = parsed;
                    g_new_sample_ready = 1;
                }
                s_cj702_idx = 0;
            }
        }
        HAL_UART_Receive_IT(&huart2, &s_rx_tmp, 1);
    }
}
